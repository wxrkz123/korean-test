def compile_patterns():
    out = []
    for pat, label, zh in G:
        ms = []
        for part in pat.split(" "):
            forms, tags = part.rsplit("/", 1)
            fs = None if forms == "*" else set(forms.split("|"))
            ts = tags.split("|")
            ms.append((fs, ts))
        out.append((ms, label, zh))
    return out

def match_all(morphs, compiled):
    """morphs: list of (form, tag, eojeol_index). returns list of (label_index, [eojeol indices])"""
    res = []
    n = len(morphs)
    for pi, (ms, label, zh) in enumerate(compiled):
        L = len(ms)
        for i in range(n - L + 1):
            ok = True
            for k, (fs, ts) in enumerate(ms):
                f, t, _ = morphs[i + k]
                if fs is not None and f not in fs: ok = False; break
                if not any(t == x or t.startswith(x + "-") for x in ts): ok = False; break
            if ok:
                res.append((pi, sorted(set(morphs[i + k][2] for k in range(L)))))
    return res
